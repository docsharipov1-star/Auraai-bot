def full_profile(full_name: str, birth_date: str) -> dict:
    lp = life_path(birth_date)
    dn = destiny_number(full_name)
    sn = soul_number(full_name)
    pn = personality_number(full_name)
    py = personal_year(birth_date)

    career_title, career_desc = LIFE_PATH_CAREER.get(lp, ("—", "—"))

    return {
        "name": full_name,
        "birth_date": birth_date,
        "life_path": lp,
        "destiny": dn,
        "soul": sn,
        "personality": pn,
        "personal_year": py,
        "career_title": career_title,
        "career_desc": career_desc,
        "soul_desc": SOUL_DESC.get(sn, "—"),
        "year_desc": PERSONAL_YEAR_DESC.get(py, "—"),
    }


