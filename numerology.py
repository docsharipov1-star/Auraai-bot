"""
Нумерология: расчёт чисел судьбы по имени и дате рождения.
Поддерживает русские и латинские имена.
"""

from datetime import datetime

# Пифагорейская система для русских букв
RU_TABLE = {
    'А':1,'Б':2,'В':6,'Г':3,'Д':4,'Е':5,'Ё':5,'Ж':2,'З':7,'И':1,'Й':1,
    'К':2,'Л':3,'М':4,'Н':5,'О':7,'П':8,'Р':9,'С':1,'Т':2,'У':6,'Ф':8,
    'Х':5,'Ц':3,'Ч':6,'Ш':2,'Щ':9,'Ъ':1,'Ы':1,'Ь':3,'Э':5,'Ю':3,'Я':1,
}

# Гласные
RU_VOWELS = set('АЕЁИОУЫЭЮЯ')
EN_VOWELS = set('AEIOU')

# Пифагорейская система для латиницы
EN_TABLE = {
    'A':1,'B':2,'C':3,'D':4,'E':5,'F':6,'G':7,'H':8,'I':9,
    'J':1,'K':2,'L':3,'M':4,'N':5,'O':6,'P':7,'Q':8,'R':9,
    'S':1,'T':2,'U':3,'V':4,'W':5,'X':6,'Y':7,'Z':8,
}

MASTER_NUMBERS = {11, 22, 33}


def _reduce(n: int) -> int:
    """Сводим к однозначному (мастер-числа 11, 22, 33 оставляем)."""
    while n > 9 and n not in MASTER_NUMBERS:
        n = sum(int(d) for d in str(n))
    return n


def life_path(birth_date: str) -> int:
    """Число жизненного пути из даты рождения (ДД.ММ.ГГГГ или ГГГГ-ММ-ДД)."""
    digits = [d for d in birth_date if d.isdigit()]
    total = sum(int(d) for d in digits)
    return _reduce(total)


def _name_value(name: str, only_vowels=False, only_consonants=False) -> int:
    name = name.upper()
    total = 0
    for ch in name:
        if ch in RU_TABLE:
            is_vowel = ch in RU_VOWELS
            if only_vowels and not is_vowel: continue
            if only_consonants and is_vowel: continue
            total += RU_TABLE[ch]
        elif ch in EN_TABLE:
            is_vowel = ch in EN_VOWELS
            if only_vowels and not is_vowel: continue
            if only_consonants and is_vowel: continue
            total += EN_TABLE[ch]
    return _reduce(total)


def destiny_number(full_name: str) -> int:
    """Число судьбы (Выражения) — полное имя."""
    return _name_value(full_name)


def soul_number(full_name: str) -> int:
    """Число души — только гласные."""
    return _name_value(full_name, only_vowels=True)


def personality_number(full_name: str) -> int:
    """Число личности — только согласные."""
    return _name_value(full_name, only_consonants=True)


def personal_year(birth_date: str, year: int | None = None) -> int:
    """Число личного года."""
    if year is None:
        year = datetime.now().year
    parts = birth_date.replace('-', '.').split('.')
    if len(parts) == 3:
        if len(parts[0]) == 4:  # ГГГГ-ММ-ДД
            day, month = parts[2], parts[1]
        else:
            day, month = parts[0], parts[1]
    else:
        return 0
    total = sum(int(d) for d in day + month + str(year))
    return _reduce(total)


