class PsychSession:
    """Сессия с психологом — хранит историю разговора."""

    def __init__(self, user_id: str):
        self.user_id = user_id
        self.history: list[dict] = []
        self.client = anthropic.AsyncAnthropic(api_key=ANTHROPIC_KEY) if ANTHROPIC_KEY else None

    async def reply(self, user_message: str) -> str:
        if not self.client:
            return "Агент не настроен — проверь ANTHROPIC_KEY."

        self.history.append({"role": "user", "content": user_message})

        response = await self.client.messages.create(
            model="claude-sonnet-4-6",
            max_tokens=600,
            system=PSYCH_SYSTEM,
            messages=self.history,
        )

        reply_text = response.content[0].text.strip()
        self.history.append({"role": "assistant", "content": reply_text})
        return reply_text

    def greeting(self) -> str:
        return (
            "Привет. Я Sage — твой психологический помощник. "
            "Здесь безопасно, всё что ты скажешь остаётся между нами. "
            "Что привело тебя сюда сегодня?"
        )

    def reset(self):
        self.history = []


# Хранилище активных сессий (в памяти, для продакшена — Redis)
_sessions: dict[str, PsychSession] = {}


def get_session(user_id: str) -> PsychSession:
    if user_id not in _sessions:
        _sessions[user_id] = PsychSession(user_id)
    return _sessions[user_id]


def reset_session(user_id: str):
    _sessions.pop(user_id, None)
